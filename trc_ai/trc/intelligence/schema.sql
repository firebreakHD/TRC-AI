PRAGMA user_version=1;
CREATE TABLE IF NOT EXISTS chats (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, profile TEXT NOT NULL, mode TEXT NOT NULL,
  archived INTEGER NOT NULL DEFAULT 0, updated TEXT NOT NULL, document TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS messages (
  id TEXT PRIMARY KEY, chat TEXT NOT NULL REFERENCES chats ON DELETE CASCADE,
  seq INTEGER NOT NULL, role TEXT NOT NULL, body TEXT NOT NULL,
  state TEXT NOT NULL DEFAULT 'done', route TEXT NOT NULL DEFAULT '',
  result TEXT NOT NULL DEFAULT '{}', created TEXT NOT NULL,
  UNIQUE(chat, seq)
);
CREATE TABLE IF NOT EXISTS attachments (
  id TEXT PRIMARY KEY, chat TEXT NOT NULL REFERENCES chats ON DELETE CASCADE,
  message TEXT REFERENCES messages ON DELETE CASCADE,
  name TEXT NOT NULL, size INTEGER NOT NULL, kind TEXT NOT NULL, digest TEXT NOT NULL,
  path TEXT, chunks TEXT NOT NULL DEFAULT '[]', created TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS configuration (
  name TEXT PRIMARY KEY, body TEXT NOT NULL
);
